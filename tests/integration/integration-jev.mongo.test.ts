test('Mongo analysis preserves frozen inputs, fences recovered workers, deduplicates results and records review revisions', async () => {
    const dbName = 'sidechannel_jev_test_' + randomUUID().replaceAll('-', '');
    const source = await MongoRepository.connect(process.env.TEST_MONGODB_URI ?? 'mongodb://127.0.0.1:27018/?directConnection=true&replicaSet=rs0', dbName);
    try {
        const repository = new MongoAnalysisRepository(source.client, source.db); await repository.initialize();
        const service = new AnalysisService(repository, source);
        const seeds = await Promise.all([service.seedCodebook(), service.seedCodebook()]);
        assert.equal(seeds[0]!.id, seeds[1]!.id);
        const unicode = { content: 'x'.repeat(65520) + '😀'.repeat(100) + '尾' };
        await repository.putArtifact('unicode-boundary', unicode);
        assert.deepEqual(await repository.readArtifact('unicode-boundary'), unicode);
        const run = createQueuedRun(defaultFixtureConfiguration(), 'jev-mongo-fixture');
        await source.createRun(run);
        await source.appendEvent({ runId: run.id, type: 'model_requested', invocationId: 'i1', agentId: 'alpha', data: { phase: 'action', messages: [] } });
        await source.appendEvent({ runId: run.id, type: 'model_response', invocationId: 'i1', agentId: 'alpha', data: { text: 'We should request authorization.', toolCalls: [] } });
        run.status = 'completed'; await source.saveRun(run);
        const original = await source.getRun(run.id);
        const book = await service.seedCodebook();
        const preview = await service.preview(run.id, { codebookId: book.id });
        const launch = { codebookId: book.id, previewHash: preview.previewHash, idempotencyKey: 'launch-1', creator: 'test' };
        const [a, b] = await Promise.all([service.launch(run.id, launch), service.launch(run.id, launch)]);
        assert.equal(a.id, b.id);
        const window = (await repository.listWindows(a.id)).items[0]!;
        const exactInput = await repository.readArtifact(window.inputRef);
        assert.match(JSON.stringify(exactInput), /request authorization/);
        const first = await repository.claim('lost-worker', new Date().toISOString(), 30000); assert(first);
        await source.db.collection('analysis_jobs').updateOne({ id: a.id }, { $set: { 'lease.expiresAt': new Date(Date.now() - 1000).toISOString() } });
        const second = await repository.claim('replacement', new Date().toISOString(), 30000); assert(second);
        assert(second.lease.fence > first.lease.fence);
        assert.equal(await repository.updateWindow(first.lease, window.id, { status: 'failed' }), false);
        const attempt: AnalysisAttempt = { id: 'attempt-1', jobId: a.id, windowId: window.id, codeIds: ['comply'], requestRef: 'request-1', startedAt: new Date().toISOString(), requestedModel: 'jev-1.14.0', status: 'running' };
        await repository.putArtifact('request-1', { state: 'fixture' });
        assert.equal(await repository.startAttempt(second.lease, attempt), true);
        const result = { id: 'result-1', jobId: a.id, windowId: window.id, codeId: 'comply', probability: 0.8, attemptId: attempt.id, createdAt: new Date().toISOString() };
        assert.equal(await repository.finishAttempt(second.lease, { ...attempt, status: 'succeeded' }, [result]), true);
        await repository.finishAttempt(second.lease, { ...attempt, status: 'succeeded' }, [{ ...result, probability: 0.1 }]);
        assert.equal((await repository.listResults(a.id)).items[0]!.probability, 0.8);
        const store = new MongoReviewStore(source.db); await store.initialize();
        const reviews = createReviewService(repository, store);
        const review = { subjectId: window.id, codeId: 'comply', definitionRevision: a.manifest.codebook.id, evidenceRevision: a.manifest.source.evidenceHash, reviewer: 'test', decision: 'present', rationale: 'Actor requests authorization.', predictionsVisible: true, eventIds: window.eventIds };
        const concurrent = await Promise.allSettled([reviews.save(a.id, review), reviews.save(a.id, review)]);
        assert.equal(concurrent.filter(r => r.status === 'fulfilled').length, 1);
        assert.equal(concurrent.filter(r => r.status === 'rejected').length, 1);
        assert.deepEqual(await source.getRun(run.id), original);
        assert.deepEqual(await repository.readArtifact(window.inputRef), exactInput);
        const exportRows = []; for await (const row of service.exportAnalysis(a.id)) exportRows.push(row);
        assert.ok(exportRows.some(row => row.type === 'artifact_chunk'));
        assert.ok(exportRows.some(row => row.type === 'result'));
        await repository.finishJob(second.lease, 'partial', a.counters);
        await service.retry(a.id);
        const submittedCodes: string[] = [];
        const worker = new AnalysisWorker(repository, { provider: { async classify(request) {
            submittedCodes.push(...request.questions.map(q => q.codeId));
            return { requestedModel: request.model!, returnedModel: 'jev-1.14.0', usage: { inputTokens: 100, outputTokens: 9 }, attempts: [], answers: request.questions.map(q => ({ codeId: q.codeId, probability: 0.25 })) };
        } } });
        await worker.runOnce();
        assert.equal((await repository.getJob(a.id))!.status, 'completed');
        assert.equal(submittedCodes.includes('comply'), false, 'retry must preserve successful probabilities');
        assert.equal((await repository.listResults(a.id)).items.length, 9);
    } finally { await source.db.dropDatabase(); await source.close(); }
});
test('Mongo codebook archive filters, paginates, guards on revision and keeps archived seeds archived', async () => {
    const dbName = 'sidechannel_jev_test_' + randomUUID().replaceAll('-', '');
    const source = await MongoRepository.connect(process.env.TEST_MONGODB_URI ?? 'mongodb://127.0.0.1:27018/?directConnection=true&replicaSet=rs0', dbName);
    try {
        const repository = new MongoAnalysisRepository(source.client, source.db); await repository.initialize();
        const service = new AnalysisService(repository, source), seed = await service.seedCodebook();
        const definitions = (await repository.getRevision(seed.id, seed.currentRevisionId))!.definitions.slice(0, 1);
        const { codebook: other } = await service.createCodebook({ name: 'Other', creator: 'test', definitions });
        const ids = async (archived?: 'exclude' | 'include' | 'only') => (await repository.listCodebooks(undefined, archived ? { archived } : undefined)).items.map(b => b.id).sort();
        const { codebook } = await service.archiveCodebook(other.id, { expectedRevisionId: other.currentRevisionId, actor: 'curator' });
        assert.equal(codebook.archivedBy, 'curator');
        assert.deepEqual(await ids(), [seed.id]); assert.deepEqual(await ids('only'), [other.id]); assert.deepEqual(await ids('include'), [seed.id, other.id].sort());
        const walked: string[] = []; let after: string | undefined;
        do { const p = await repository.listCodebooks({ limit: 1, after }, { archived: 'include' }); walked.push(...p.items.map(b => b.id)); after = p.nextCursor ?? undefined; } while (after);
        assert.deepEqual(walked, [seed.id, other.id].sort());
        await assert.rejects(service.archiveCodebook(other.id, { expectedRevisionId: other.currentRevisionId, actor: 'curator' }), /already archived/);
        await assert.rejects(service.reviseCodebook(other.id, { creator: 'e', definitions, expectedRevisionId: other.currentRevisionId }), /archived/);
        await assert.rejects(repository.setCodebookArchived(seed.id, 'stale', { archivedAt: new Date().toISOString(), archivedBy: 'x' }), /revision changed/);
        await assert.rejects(repository.setCodebookArchived('missing', 'x', null), /not found/);
        const restored = (await service.restoreCodebook(other.id, { expectedRevisionId: other.currentRevisionId, actor: 'curator' })).codebook;
        assert.equal('archivedAt' in restored, false); assert.deepEqual(await ids('only'), []);
        await service.archiveCodebook(seed.id, { expectedRevisionId: seed.currentRevisionId, actor: 'curator' });
        assert.ok((await service.seedCodebook()).archivedAt); assert.deepEqual(await ids('only'), [seed.id]);
        const { codebook: race } = await service.createCodebook({ name: 'Race', creator: 'test', definitions });
        const stale = (await repository.getCodebook(race.id))!;
        await service.archiveCodebook(race.id, { expectedRevisionId: race.currentRevisionId, actor: 'curator' });
        const lateRevision = { id: randomUUID(), codebookId: race.id, revision: 2, createdAt: new Date().toISOString(), createdBy: 'late', definitions };
        await assert.rejects(repository.saveCodebook({ ...stale, currentRevisionId: lateRevision.id }, lateRevision, race.currentRevisionId), /revision changed/);
        await assert.rejects(repository.setCodebookArchived(race.id, race.currentRevisionId, { archivedAt: new Date().toISOString(), archivedBy: 'second' }), /revision changed/);
        const kept = (await repository.getCodebook(race.id))!; assert.equal(kept.archivedBy, 'curator'); assert.equal(kept.currentRevisionId, race.currentRevisionId);
    } finally { await source.db.dropDatabase(); await source.close(); }
});
